  word(73, "3", "1つのポットに6.45Lずつお茶を入れます。14個のポットでは何L必要？",
    ["6.45×14", "6.45÷14", "6.45＋14"], 0, 90.3, "L");
  operators(73, [0.3,0.7,0.5,0.6,0.8,0.9], 1);

  // 74〜75：小数のかけ算まとめテスト。
  multiplied(74, "1", [[0.7,8],[1.3,2],[1.2,3],[0.5,8]]);
  multiplied(74, "2", [[3.8,2],[9.7,6],[26.8,3],[46.5,4],[1.9,42],
    [5.6,79],[70.4,63],[62.5,48],[9.36,7],[8.92,45]]);
  multiplied(75, "3", [[8.4,9],[47.3,8],[12.5,4],[6.38,3],[56.9,74],[7.42,65]]);
  word(75, "4", "毎日3.5km走る人は、42日間で何km走る？",
    ["3.5×42", "3.5÷42", "42－3.5"], 0, 147, "km");
  puzzle(75, "道に80cm間隔でくいを打ち、最初と最後のくいもロープでつなぐと、長さ9m60cmでした。くいは何本？", 13, "本");

  // 76〜77：小数÷一けた。ページの重複スキャンを照合して転記。
