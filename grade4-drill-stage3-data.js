  divided(76, "2", [[8.4,2],[7.2,3],[7.8,6],[9.5,5],[42.3,9],[39.2,7]]);
  divided(77, "2", [[50.4,8],[19.4,2],[83.5,5],[55.6,4],[76.8,6],[73.8,3],[3.6,4],[5.6,7]]);
