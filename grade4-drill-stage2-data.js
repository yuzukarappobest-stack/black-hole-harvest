  function frac(page, step, whole1, num1, den, op, whole2, num2) {
    const left = { whole: whole1, numerator: num1, denominator: den };
    const right = { whole: whole2, numerator: num2, denominator: den };
    const n1 = whole1 * den + num1;
    const n2 = whole2 * den + num2;
    const numerator = op === "+" ? n1 + n2 : n1 - n2;
    if (numerator < 0) throw new Error(`負の分数: p${page}`);
    add(page, step, { kind: "fraction", left, operator: op, right,
      answer: { numerator, denominator: den } });
  }
  function fractionPair(page, step, op, den, pairs) {
    pairs.forEach(([n1, n2]) => frac(page, step, 0, n1, den, op, 0, n2));
  }
  function mixed(page, step, op, rows) {
    rows.forEach(([w1, n1, d, w2, n2]) => frac(page, step, w1, n1, d, op, w2, n2));
  }
